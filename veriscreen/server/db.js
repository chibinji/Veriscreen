import mysql from 'mysql2/promise';
import pg from 'pg';
import bcrypt from 'bcryptjs';

const config = {
  host: process.env.DB_HOST || 'localhost',
  port: Number(process.env.DB_PORT || 3306),
  user: process.env.DB_USER || 'root',
  password: process.env.DB_PASSWORD || '',
  database: process.env.DB_NAME || 'veriscreen_db',
};

const databaseUrl = process.env.DATABASE_URL || '';
const usePostgres = databaseUrl.startsWith('postgres');
const schema = /^[a-z_]+$/.test(process.env.DB_SCHEMA || '') ? process.env.DB_SCHEMA : 'veriscreen';

function createPool() {
  if (!usePostgres) {
    return mysql.createPool({ ...config, waitForConnections: true, connectionLimit: 10 });
  }
  const pgPool = new pg.Pool({
    connectionString: databaseUrl,
    ssl: /render\.com|sslmode=require/.test(databaseUrl) ? { rejectUnauthorized: false } : undefined,
    options: `-c search_path=${schema}`,
  });
  return {
    async query(sql, params = []) {
      let index = 0;
      let text = String(sql).replace(/\?/g, () => `$${++index}`);
      if (/^\s*insert\b/i.test(text) && !/\breturning\b/i.test(text)) text += ' RETURNING id';
      const result = await pgPool.query(text, params);
      if (/^\s*insert\b/i.test(sql)) return [{ insertId: result.rows[0]?.id, affectedRows: result.rowCount }];
      if (/^\s*(update|delete)\b/i.test(sql)) return [{ affectedRows: result.rowCount }];
      return [result.rows];
    },
  };
}

export const pool = createPool();

function postgresSchema(sql) {
  return sql
    .replace(/INT AUTO_INCREMENT PRIMARY KEY/g, 'INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/TINYINT\(1\)/g, 'SMALLINT')
    .replace(/DATETIME/g, 'TIMESTAMP');
}

